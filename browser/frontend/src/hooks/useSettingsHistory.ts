import { useEffect } from 'react';
import { useBrowserStore, type BrowserState } from '../stores/browserStore';
import { CLASS_REGION_CHOICE_LABEL } from '../utils/classRegion';
import { sameHistoryState, serializeState, type SerializedState, type SnapshotKind } from '../stores/historySlice';
import { storeExtensions } from '../stores/storeExtensions';

/** Wait for this long without changes (e.g. a dragged slider) before recording one undo step. */
const SETTLE_MS = 800;

interface WatchedSetting {
  key: string;
  kind: SnapshotKind;
  /** A value that changes exactly when the user changed this setting. */
  signature: (s: BrowserState) => unknown;
  label: (s: BrowserState) => string;
}

// Labeling, edges and quality filters record their own undo steps (colormapSlice).
/** Store fields the watched settings read from. */
const CORE_SLICES = ['footprintGroups', 'classRegionMode'] as const;
const CORE_WATCHED: WatchedSetting[] = [
  {
    // Classes regenerated on every pan are not user edits.
    key: 'saved', kind: 'analysis',
    signature: s => JSON.stringify(s.footprintGroups.filter(g => !g.autoGeneratedFamily)),
    label: () => 'Saved footprints',
  },
  {
    // Footprints › Classes: which region Find classes analyses (utils/classRegion.ts).
    key: 'class-region', kind: 'analysis',
    signature: s => s.classRegionMode,
    label: s => `Find classes in: ${CLASS_REGION_CHOICE_LABEL[s.classRegionMode] ?? s.classRegionMode}`,
  },
];

/** The watched settings: core's and plugin packs' (stores/storeExtensions.ts). */
function watched(): { slices: string[]; settings: WatchedSetting[] } {
  const extra = storeExtensions().flatMap(ext => ext.settingsHistory ?? []);
  return { slices: [...CORE_SLICES, ...extra.map(w => w.slice)], settings: [...CORE_WATCHED, ...extra] };
}

function shallowEqualObjects(a: unknown, b: unknown): boolean {
  if (a === b) return true;
  if (!a || !b || typeof a !== 'object' || typeof b !== 'object') return false;
  const ak = Object.keys(a as object);
  const bk = Object.keys(b as object);
  return ak.length === bk.length && ak.every(k => (a as Record<string, unknown>)[k] === (b as Record<string, unknown>)[k]);
}

// Theme and UI size are not undo steps: a change of them alone is no difference.
function sameState(a: SerializedState | undefined, b: SerializedState): boolean {
  return sameHistoryState(a, b);
}

/**
 * Undo for saved footprint entries edited in place (added, renamed, resized,
 * toggled, removed): one undo step shortly after each change,
 * with a "Before …" step first when the history doesn't already hold the
 * earlier state.
 */
export function useSettingsHistory(): void {
  useEffect(() => {
    const timers = new Map<string, number>();
    const { slices: WATCHED_SLICES, settings: WATCHED } = watched();
    const unsubscribe = useBrowserStore.subscribe((state, prev) => {
      // Runs on every store update: bail out unless a watched slice changed.
      if (WATCHED_SLICES.every(slice => (state as unknown as Record<string, unknown>)[slice] === (prev as unknown as Record<string, unknown>)[slice])) return;
      if (Date.now() - state._lastRestoreTime < 1500 || state._historyPaused) return; // an undo/redo
      for (const watched of WATCHED) {
        const before = watched.signature(prev);
        const after = watched.signature(state);
        if (before === after || shallowEqualObjects(before, after)) continue;
        if (!timers.has(watched.key)) {
          // First change of a burst: make sure undo can return to the state before it.
          const stack = state._historyStack;
          const current = stack[state._historyPointer];
          const previous = serializeState(prev);
          if (!current || !sameState(current.state, previous)) {
            state.pushSerializedSnapshot(`Before ${watched.label(prev).toLowerCase()}`, previous, {
              kind: watched.kind, coalesceKey: `baseline-${watched.key}-${Date.now()}`,
            });
          }
        } else {
          window.clearTimeout(timers.get(watched.key));
        }
        timers.set(watched.key, window.setTimeout(() => {
          timers.delete(watched.key);
          const now = useBrowserStore.getState();
          if (Date.now() - now._lastRestoreTime < 1500) return;
          const top = now._historyStack[now._historyPointer];
          if (top && sameState(top.state, serializeState(now))) return; // already recorded
          now.pushSnapshot(watched.label(now), { kind: watched.kind, coalesceKey: `settings-${watched.key}` });
        }, SETTLE_MS));
      }
    });
    return () => {
      unsubscribe();
      for (const timer of timers.values()) window.clearTimeout(timer);
    };
  }, []);
}
