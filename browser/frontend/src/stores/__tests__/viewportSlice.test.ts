describe('bookmarks', () => {
  it('addBookmark adds a bookmark at current position', () => {
    store.setState({ chrom: 'chr1', start: 100, end: 200 });
    store.getState().addBookmark('Test');
    const bm = store.getState().bookmarks;
    expect(bm).toHaveLength(1);
    expect(bm[0].name).toBe('Test');
    expect(bm[0].chrom).toBe('chr1');
    expect(bm[0].start).toBe(100);
    expect(bm[0].end).toBe(200);
  });

  it('removeBookmark removes by ID', () => {
    store.getState().addBookmark('Test1');
    // Ensure unique IDs by directly setting bookmarks with known IDs
    const bm1 = store.getState().bookmarks[0];
    store.setState({
      bookmarks: [
        bm1,
        { id: 'bookmark_unique_2', name: 'Test2', chrom: 'chr1', start: 0, end: 1000, created: new Date().toISOString() },
      ],
    });
    store.getState().removeBookmark(bm1.id);
    expect(store.getState().bookmarks).toHaveLength(1);
    expect(store.getState().bookmarks[0].name).toBe('Test2');
  });

  it('navigateToBookmark sets viewport', () => {
    store.setState({ chrom: 'chr1', start: 0, end: 1000 });
    store.getState().addBookmark('MyRegion');
    store.setState({ chrom: 'chr2', start: 5000, end: 6000 });

    const id = store.getState().bookmarks[0].id;
    store.getState().navigateToBookmark(id);
    expect(store.getState().chrom).toBe('chr1');
    expect(store.getState().start).toBe(0);
  });

  it('updateBookmark modifies bookmark name', () => {
    store.getState().addBookmark('Old Name');
    const id = store.getState().bookmarks[0].id;
    store.getState().updateBookmark(id, { name: 'New Name' });
    expect(store.getState().bookmarks[0].name).toBe('New Name');
  });
});

