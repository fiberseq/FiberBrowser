// ============================================================================
// setViewport — Chrom changes
// ============================================================================

describe('setViewport - chrom change', () => {
  it('clears all selections when chromosome changes', () => {
    const s = store.getState();
    // Set up some state
    store.setState({
      selectedPeaks: new Set([0, 1]),
      clusterAssignments: { ds1: { r1: 0, r2: 1 } },
      selectedClusters: { ds1: new Set([1]) },
      dynamicClustering: true,
    });

    store.getState().setViewport('chr3', 0, 1000);

    const after = store.getState();
    expect(after.chrom).toBe('chr3');
    expect(after.selectedPeaks.size).toBe(0);
    expect(after.clusterAssignments).toEqual({});
    expect(after.selectedClusters).toEqual({});
    expect(after.dynamicClustering).toBe(false);
  });

  it('keeps saved footprint definitions on chrom change (pinning positional ones), dropping view-derived families', () => {
    const chromBefore = store.getState().chrom;
    store.setState({
      footprintGroups: [
        { id: 'g1', name: 'test', color: '#f00', sourceIndex: 0, sizeMin: 0, sizeMax: 100, overlapFraction: 0.5, enabled: true },
        { id: 'g2', name: 'pinned', color: '#0f0', sourceIndex: -1, sizeMin: 10, sizeMax: 60, enabled: true, referenceAbsStart: 100, referenceAbsEnd: 150 },
        { id: 'g3', name: 'family', color: '#00f', sourceIndex: -1, sizeMin: 10, sizeMax: 60, enabled: true, autoGeneratedFamily: true, sourceViewKey: 'v' },
      ],
    } as never);
    store.getState().setViewport('chr5', 0, 1000);
    const groups = store.getState().footprintGroups;
    expect(groups.map(g => g.id)).toEqual(['g1', 'g2']);
    expect(groups[0].referenceChrom).toBeUndefined();
    expect(groups[1].referenceChrom).toBe(chromBefore);
  });

  it('clears gene selection on chrom change', () => {
    store.setState({
      selectedGenes: [{ id: 'gene1', name: 'TP53', chrom: 'chr1', start: 100, end: 500, strand: '+', biotype: 'protein_coding', exons: [] }],
    });
    store.getState().setViewport('chr2', 0, 1000);
    expect(store.getState().selectedGenes).toEqual([]);
  });
});

