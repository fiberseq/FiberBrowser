describe('viewport history', () => {
  it('pushViewportHistory adds entry', () => {
    store.getState().pushViewportHistory({ chrom: 'chr1', start: 0, end: 1000 });
    expect(store.getState().viewportHistory).toHaveLength(1);
  });

  it('pushViewportHistory deduplicates identical entries', () => {
    store.getState().pushViewportHistory({ chrom: 'chr1', start: 0, end: 1000 });
    store.getState().pushViewportHistory({ chrom: 'chr1', start: 0, end: 1000 });
    expect(store.getState().viewportHistory).toHaveLength(1);
  });

  it('pushViewportHistory limits to 50 entries', () => {
    for (let i = 0; i < 60; i++) {
      store.getState().pushViewportHistory({ chrom: 'chr1', start: i * 1000, end: (i + 1) * 1000 });
    }
    expect(store.getState().viewportHistory.length).toBeLessThanOrEqual(50);
  });

  it('goBack navigates to previous entry', () => {
    store.setState({ chrom: 'chr1', start: 0, end: 1000 });
    store.getState().pushViewportHistory({ chrom: 'chr1', start: 0, end: 1000 });
    store.setState({ chrom: 'chr1', start: 5000, end: 6000 });

    store.getState().goBack();
    const after = store.getState();
    expect(after.start).toBe(0);
    expect(after.end).toBe(1000);
  });

  it('goForward returns to next entry', () => {
    // Set current position, push it to history, then navigate away
    store.setState({ chrom: 'chr1', start: 0, end: 1000 });
    store.getState().pushViewportHistory({ chrom: 'chr1', start: 0, end: 1000 });
    // Move to a new position
    store.setState({ chrom: 'chr1', start: 5000, end: 6000 });
    // goBack from head: pushes current (5000-6000) to history, navigates to previous (0-1000)
    store.getState().goBack();
    expect(store.getState().start).toBe(0);
    // goForward: returns to the pushed current (5000-6000)
    store.getState().goForward();
    const after = store.getState();
    expect(after.start).toBe(5000);
    expect(after.end).toBe(6000);
  });

  it('Back, Forward, Back returns to the previous view again', () => {
    store.setState({ chrom: 'chr1', start: 0, end: 1000 });
    store.getState().pushViewportHistory({ chrom: 'chr1', start: 0, end: 1000 });
    store.setState({ chrom: 'chr1', start: 5000, end: 6000 });

    store.getState().goBack();
    store.getState().goForward();
    expect(store.getState().start).toBe(5000);
    expect(store.getState().canGoForward()).toBe(false);
    store.getState().goBack();
    expect(store.getState().start).toBe(0);
  });

  it('navigating on after Forward reaches the last entry goes back to it first', () => {
    store.setState({ chrom: 'chr1', start: 0, end: 1000 });
    store.getState().pushViewportHistory({ chrom: 'chr1', start: 0, end: 1000 });
    store.setState({ chrom: 'chr1', start: 5000, end: 6000 });
    store.getState().goBack();
    store.getState().goForward();
    // A normal navigation away from 5000-6000 records it (already the last entry).
    store.getState().pushViewportHistory({ chrom: 'chr1', start: 5000, end: 6000 });
    store.setState({ chrom: 'chr1', start: 9000, end: 10000 });
    store.getState().goBack();
    expect(store.getState().start).toBe(5000);
  });

  it('canGoBack returns false when no history', () => {
    expect(store.getState().canGoBack()).toBe(false);
  });

  it('canGoForward returns false at head', () => {
    expect(store.getState().canGoForward()).toBe(false);
  });
});

