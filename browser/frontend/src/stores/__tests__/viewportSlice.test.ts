describe('setViewport - normal pan', () => {
  it('keeps sorted read order on same-chrom pan and zoom', () => {
    store.setState({
      chrom: 'chr1',
      start: 1000,
      end: 2000,
      readSortOrder: { ds1: ['r1', 'r2'] },
    });
    store.getState().setViewport('chr1', 1500, 2500);
    expect(store.getState().readSortOrder).toEqual({ ds1: ['r1', 'r2'] });
    store.getState().setViewport('chr1', 1700, 2300);
    expect(store.getState().readSortOrder).toEqual({ ds1: ['r1', 'r2'] });
    store.getState().setViewport('chr1', 50000, 60000);
    expect(store.getState().readSortOrder).toEqual({});
  });

  it('clears selections when no peaks are visible', () => {
    store.setState({
      chrom: 'chr1',
      start: 0,
      end: 1000,
      selectedPeaks: new Set([0]),
      peaksByRule: { ...store.getState().peaksByRule, 'default-accessibility': [{ start: 100, end: 200, index: 0 }] },
    });
    // Pan far away from peak
    store.getState().setViewport('chr1', 50000, 60000);
    expect(store.getState().selectedPeaks.size).toBe(0);
  });

  it('preserves locked peaks across same-chrom pans', () => {
    store.setState({
      chrom: 'chr1',
      start: 0,
      end: 500,
      peaksLocked: true,
      peaksByRule: {
        'default-accessibility': [{ start: 100, end: 200, index: 0, layer: 0 }],
      },
      selectedPeaks: new Set([0]),
      clusterAssignments: { ds1: { r1: 0 } },
    });

    store.getState().setViewport('chr1', 1000, 2000);

    const after = store.getState();
    expect(after.peaksLocked).toBe(true);
    expect(after.peaksByRule['default-accessibility']).toHaveLength(1);
    expect(after.selectedPeaks.has(0)).toBe(true);
    expect(after.clusterAssignments).toEqual({});
  });
});

