import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { expect, it, vi } from 'vitest';
import { ProposalList } from './ProposalList';
import type { Proposal, SyncResult } from './model';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const p = (id: string, extra: Partial<Proposal> = {}): Proposal => ({ id, panelId: 'b', partnerId: 'a', rank: 0, template: [100, 800], window: [1100, 1800], strand: '+', sources: ['sequence'], metrics: { sequence: { verdict: 'supports', score: .98 }, nfr: { verdict: 'weak', score: .12 } }, status: 'single-metric', confidence: .7, supports: 1, assessed: 2, ...extra });
it('lists proposals with per-metric verdicts, selects with arrows and offers rotation and template switching', async () => {
  const proposals = [p('one', { flags: ['repeat', 'crosses-origin', 'indels'], alternatives: 2, crosses: ['window'], blocks: [{ template: [100, 400], window: [1100, 1400] }, { template: [400, 800], window: [2829, 3229] }], gaps: [{ template: 6832, window: 1400, inserted: 1429, deleted: 0 }], indels: { inserted: 1429, deleted: 0, count: 1 } }), p('two'), p('other', { partnerId: 'b', panelId: 'c' })];
  const result: SyncResult = { metrics: ['sequence', 'nfr'], windows: ['a', 'b', 'c'].map(id => ({ panelId: id, datasetId: id, label: id.toUpperCase(), genome: null, chrom: 'chr1', start: 0, end: 2000 })), proposals, coverage: {}, notes: [] };
  const node = document.createElement('div');
  document.body.appendChild(node);
  const root = createRoot(node);
  const focus = vi.fn(), rotate = vi.fn(), useTemplate = vi.fn();
  await act(async () => root.render(<ProposalList result={result} proposals={proposals} focusedId="one" onFocus={focus} onRotate={rotate} onUseTemplate={useTemplate} hidden={4} />));
  const row = node.querySelector<HTMLElement>('[data-testid="sync-proposal-one"]')!;
  expect(row.getAttribute('aria-selected')).toBe('true');
  expect(row.textContent).toContain('100–800 ↔ 1,100–1,800');
  expect(row.textContent).toContain('Seq 98%');
  expect(row.textContent).toContain('NFR r 0.12');
  expect(row.textContent).toContain('3 places in W2 match this stretch');
  expect(row.textContent).toContain('crosses W2’s origin');
  await act(async () => row.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true })));
  expect(focus).toHaveBeenLastCalledWith(proposals[1]);
  // The Rotate button sits outside the option, so its keys never select the row.
  const rotateButton = node.querySelector<HTMLElement>('[data-testid="sync-rotate-one"]')!;
  expect(rotateButton.closest('[role="option"]')).toBeNull();
  await act(async () => rotateButton.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })));
  expect(focus).toHaveBeenCalledTimes(1);
  await act(async () => rotateButton.dispatchEvent(new MouseEvent('click', { bubbles: true })));
  expect(rotate).toHaveBeenCalledWith(proposals[0], 'window');
  expect(row.textContent).toContain('+1,429 bp in W2 at 6,832');
  expect(row.textContent).toContain('chain of 2 blocks');
  expect(focus).toHaveBeenCalledTimes(1);
  await act(async () => node.querySelector<HTMLElement>('[data-testid="sync-use-template-b"]')!.dispatchEvent(new MouseEvent('click', { bubbles: true })));
  expect(useTemplate).toHaveBeenCalledWith('b');
  expect(node.textContent).toContain('4 weaker proposals hidden.');
  await act(async () => root.unmount());
  node.remove();
});
