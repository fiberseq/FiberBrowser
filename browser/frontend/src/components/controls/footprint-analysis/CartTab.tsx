interface CartTabProps {
  footprintGroups: FootprintGroup[];
  setFootprintGroups: (groups: FootprintGroup[]) => void;
  updateFootprintGroup: (id: string, updates: Partial<FootprintGroup>) => void;
  removeFootprintGroup: (id: string) => void;
  /** When set, this entry is currently driving the read-filter state. */
  activeFilterId: string | null;
  onApplyFilter: (group: FootprintGroup) => void;
  /** A saved recaller class (all its entries) as one filter. */
  onFilterSavedClass?: (groups: FootprintGroup[]) => void;
  onClearFilter: () => void;
  /** Dataset IDs currently targeted by the analysis panel. */
  targetDatasetIds: string[];
  /** Width hint passed through to the inline charts. */
  chartWidth: number;
}

type CartMessage = {
  kind: AnalysisStatusKind;
  text: string;
};


/** Saved footprint definitions (found states and size rules).
 *
 *  Each entry is a `FootprintGroup`: name + color + layer + size range +
 *  optional reference overlap. Drives:
 *    - read-track coloring (handled by the canvas color logic)
 *    - cross-highlight (handled by the canvas highlight loop)
 *    - filter-by-occupancy (this tab — "Apply" button sets filteredReadIds)
 *    - co-occupancy across pairs (Co-occ tab)
 *
 *  Persists across viewport changes + reloads via localStorage.
 */
export function CartTab({
  footprintGroups,
  setFootprintGroups,
  updateFootprintGroup,
  removeFootprintGroup,
  activeFilterId,
  onApplyFilter,
  onFilterSavedClass,
  onClearFilter,
  targetDatasetIds,
  chartWidth,
}: CartTabProps) {
  const showDetails = useBrowserStore(s => s.showAnalysisDetails);
  const [expandedId, setExpandedId] = useState<string | null>(null);
  const [exporting, setExporting] = useState(false);
  const [savingRules, setSavingRules] = useState(false);
  const [loadingRules, setLoadingRules] = useState(false);
  const [attachingCalls, setAttachingCalls] = useState(false);
  const [exportingCalls, setExportingCalls] = useState(false);
  const [cartMessage, setCartMessage] = useState<CartMessage | null>(null);
  /** Bases of flanking sequence added on each side of every cart entry's
   *  reference at FASTA export time. Defaults to 0 (just the footprint). */
  const [exportFlank, setExportFlank] = useState(0);
  const {
    datasets, chrom, start, end, spanningOnly,
    analysisSampleCount, analysisSampleSeed, setDatasets,
    selectedFamilyGroupId, setSelectedFamilyGroupId,
  } = useBrowserStore(useShallow(s => ({
    datasets: s.datasets,
    chrom: s.chrom,
    start: s.start,
    end: s.end,
    spanningOnly: s.spanningOnly,
    analysisSampleCount: s.analysisSampleCount,
    analysisSampleSeed: s.analysisSampleSeed,
    setDatasets: s.setDatasets,
    selectedFamilyGroupId: s.selectedFamilyGroupId,
    setSelectedFamilyGroupId: s.setSelectedFamilyGroupId,
  })));

  useEffect(() => {
    // Only listed entries can be expanded (auto families are not listed).
    if (
      selectedFamilyGroupId
      && footprintGroups.some(group => group.id === selectedFamilyGroupId && !group.autoGeneratedFamily)
    ) {
      setExpandedId(selectedFamilyGroupId);
    }
  }, [selectedFamilyGroupId, footprintGroups]);

  const defaultBundleName = `footprints_${chrom}_${start}-${end}`;
  const attachDatasetIds = targetDatasetIds.length > 0 ? targetDatasetIds : datasets.map(dataset => dataset.id);
  const showCartMessage = (kind: AnalysisStatusKind, text: string) => {
    setCartMessage({ kind, text });
  };
  const clearCartMessage = () => setCartMessage(null);
  // Auto-discovered families from tagged BAMs are regenerated on every pan and
  // only drive read coloring; listing them here was noise.
  const visibleGroups = footprintGroups.filter(group => !group.autoGeneratedFamily);
  // A saved class is one definition however many datasets/strands it covers.
  const definitionCount = visibleGroups.filter(g => !g.savedClass).length + new Set(visibleGroups.flatMap(g => g.savedClass ? [g.savedClass.id] : [])).size;

  /** Bulk-fetch reference sequences for every cart entry that has a pinned
   *  reference, then assemble a FASTA file and trigger a download. Each
   *  record is `>name chrom:start-end\nSEQUENCE`. Compatible with MEME,
   *  HOMER, FIMO, BLAST, and any other tool that accepts FASTA. */
  const handleExportFasta = async () => {
    const targets = visibleGroups.filter(g => g.referenceAbsStart != null && g.referenceAbsEnd != null);
    if (targets.length === 0) return;
    setExporting(true);
    clearCartMessage();
    try {
      const flank = Math.max(0, exportFlank);
      const sequences: (string | undefined)[] = [];
      const seqStarts: (number | undefined)[] = [];
      // Definitions may share chromosome names while belonging to different references.
      for (const [targetIndex, group] of targets.entries()) {
        const source = footprintSource(useBrowserStore.getState(), group, attachDatasetIds);
        const dsId = source.datasetIds[0];
        if (!dsId) continue;
        const bases = basesCovering(group.referenceAbsStart!, group.referenceAbsEnd!);
        const res = await analyzeFootprints(source.chrom, Math.max(0, bases.start - flank), bases.end + flank, spanningOnly,
          [{ absStart: bases.start, absEnd: bases.end, size: bases.end - bases.start, readId: '__cart_export__', datasetId: dsId }],
          [dsId], { panelGenome: source.genome, autoMotifs: false, flankBp: flank, profileWindow: 100,
            readAnalysis: false, motifs: false, maxReads: analysisSampleCount ?? undefined, sampleSeed: analysisSampleSeed });
        const fp = orientFootprint(res.footprints[0], source.reversed);
        sequences[targetIndex] = fp?.sequence ?? undefined;
        seqStarts[targetIndex] = fp?.seq_start;
      }
      // Build FASTA. Use entry name as primary header, fall back to coords.
      const lines: string[] = [];
      for (let i = 0; i < targets.length; i++) {
        const g = targets[i];
        const seq = sequences[i];
        if (!seq) continue;
        const safeName = (g.name || 'cart_entry').replace(/\s+/g, '_').replace(/[^\w.-]/g, '');
        // The coordinates of the bases returned: the flanked span, clipped by the
        // backend at either end of the reference (seq_start is where it began).
        const headerStart = seqStarts[i] ?? Math.max(0, Math.floor(g.referenceAbsStart!) - flank);
        const headerEnd = headerStart + seq.length;
        const header = `>${safeName} ${g.referenceChrom || chrom}:${headerStart}-${headerEnd}`;
        lines.push(header);
        // Wrap to 70 chars per FASTA convention
        for (let j = 0; j < seq.length; j += 70) lines.push(seq.slice(j, j + 70));
      }
      if (lines.length === 0) {
        showCartMessage('warning', 'No sequences returned. Check that the FASTA covers these regions.');
        return;
      }
      const blob = new Blob([lines.join('\n') + '\n'], { type: 'text/plain' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `footprints_${chrom}_${start}-${end}.fa`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
      showCartMessage('success', `Exported ${targets.length} saved sequence${targets.length === 1 ? '' : 's'} as FASTA.`);
    } catch (e) {
      console.error('Cart FASTA export failed:', e);
      showCartMessage('error', `Export failed: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      setExporting(false);
    }
  };

  const handleSaveDerivedLayers = async () => {
    const enabledGroups = visibleGroups.filter(g => g.enabled);
    if (enabledGroups.length === 0) {
      showCartMessage('warning', 'No enabled saved definitions to export.');
      return;
    }
    if (targetDatasetIds.length === 0) {
      showCartMessage('warning', 'No target datasets are loaded.');
      return;
    }

    setExportingCalls(true);
    clearCartMessage();
    try {
      const picked = await pickFolder('Select folder for derived-layer bundle');
      if (!picked.success || !picked.path) {
        showCartMessage('info', picked.message || 'Export cancelled.');
        return;
      }
      const res = await exportDerivedLayers(chrom, start, end, spanningOnly, {
        dataset_ids: targetDatasetIds,
        groups: enabledGroups,
        output_dir: picked.path,
        bundle_name: defaultBundleName,
        sample_seed: analysisSampleSeed,
      });
      if (res.datasets) {
        setDatasets(res.datasets);
      }
      const saved = (res.bundles || []).filter(bundle => bundle.n_rows > 0);
      const bigbeds = saved.filter(bundle => bundle.bigbed_path).length;
      const warningText = res.warnings?.length ? ` Warning: ${res.warnings.join('; ')}` : '';
      if (!res.success || saved.length === 0) {
        showCartMessage('warning', res.error || 'No intervals matched the enabled saved definitions.');
        return;
      }
      showCartMessage('success',
        `Exported ${saved.length} materialized call bundle${saved.length === 1 ? '' : 's'} (${bigbeds} BigBed${bigbeds === 1 ? '' : 's'}).${warningText}`
      );
    } catch (e) {
      console.error('Materialized call export failed:', e);
      const message = e instanceof Error ? e.message : String(e);
      showCartMessage('error', `Export failed: ${message}`);
    } finally {
      setExportingCalls(false);
    }
  };

  const handleAttachDerivedLayers = async () => {
    if (attachDatasetIds.length === 0) {
      showCartMessage('warning', 'Load a BAM/BigBed dataset before attaching materialized calls.');
      return;
    }

    setAttachingCalls(true);
    clearCartMessage();
    try {
      const picked = await pickFile('fiberlayers');
      if (!picked.success || !picked.path) {
        showCartMessage('info', picked.message || 'Attach cancelled.');
        return;
      }
      const res = await loadDerivedLayers(picked.path, attachDatasetIds);
      if (res.datasets) {
        setDatasets(res.datasets);
      }
      if (!res.success) {
        showCartMessage('warning', res.error || 'No loaded dataset matched that materialized call bundle.');
        return;
      }
      const attachedCount = (res.attached || []).reduce((sum, entry) => sum + entry.layer_ids.length, 0);
      const warningText = res.warnings?.length ? ` Warning: ${res.warnings.join('; ')}` : '';
      showCartMessage(res.warnings?.length ? 'warning' : 'success',
        `Attached ${attachedCount} materialized call layer${attachedCount === 1 ? '' : 's'} from ${picked.path.split('/').pop()}.${warningText}`
      );
    } catch (e) {
      console.error('Materialized call attach failed:', e);
      const message = e instanceof Error ? e.message : String(e);
      showCartMessage('error', `Attach failed: ${message}`);
    } finally {
      setAttachingCalls(false);
    }
  };

  const handleSaveRules = async () => {
    if (visibleGroups.length === 0) {
      showCartMessage('warning', 'No saved definitions to export.');
      return;
    }

    setSavingRules(true);
    clearCartMessage();
    try {
      const picked = await pickFolder('Select folder for footprint rule JSON');
      if (!picked.success || !picked.path) {
        showCartMessage('info', picked.message || 'Save cancelled.');
        return;
      }
      const res = await saveFootprintRules({
        groups: visibleGroups,
        output_dir: picked.path,
        bundle_name: defaultBundleName,
        chrom,
        start,
        end,
        spanning: spanningOnly,
        dataset_ids: targetDatasetIds,
        sample_seed: analysisSampleSeed,
      });
      if (!res.success) {
        showCartMessage('warning', res.error || 'Could not save footprint rules.');
        return;
      }
      showCartMessage('success', `Saved ${res.n_rules ?? visibleGroups.length} rule${(res.n_rules ?? visibleGroups.length) === 1 ? '' : 's'} to ${res.path?.split('/').pop() || 'rule JSON'}.`);
    } catch (e) {
      console.error('Footprint rule save failed:', e);
      const message = e instanceof Error ? e.message : String(e);
      showCartMessage('error', `Save failed: ${message}`);
    } finally {
      setSavingRules(false);
    }
  };

  const handleLoadRules = async (mode: 'replace' | 'append') => {
    setLoadingRules(true);
    clearCartMessage();
    try {
      const picked = await pickFile('footprint_rules');
      if (!picked.success || !picked.path) {
        showCartMessage('info', picked.message || 'Load cancelled.');
        return;
      }
      const res = await loadFootprintRules(picked.path);
      if (!res.success || !res.groups) {
        showCartMessage('warning', res.error || 'Could not load footprint rules.');
        return;
      }
      const replace = visibleGroups.length === 0 || mode === 'replace';
      // Read the store now: the file dialog was open while other panels could
      // change the list. Hidden auto-discovered families always survive.
      const current = useBrowserStore.getState().footprintGroups;
      const kept = replace ? current.filter(group => group.autoGeneratedFamily) : current;
      const normalized = normalizeFootprintGroups(res.groups);
      // Appended saved classes are renumbered after the ones already here (S1 stays unique).
      const loaded = replace
        ? normalized
        : remapSavedClassIds(normalized, kept).map(group => ({ ...group, id: crypto.randomUUID() }));
      setFootprintGroups([...kept, ...loaded]);
      showCartMessage('success', `${replace ? 'Loaded' : 'Appended'} ${loaded.length} rule${loaded.length === 1 ? '' : 's'} from ${picked.path.split('/').pop()}.`);
    } catch (e) {
      console.error('Footprint rule load failed:', e);
      const message = e instanceof Error ? e.message : String(e);
      showCartMessage('error', `Load failed: ${message}`);
    } finally {
      setLoadingRules(false);
    }
  };

  const pinnedCount = visibleGroups.filter(g => g.referenceAbsStart != null && g.referenceAbsEnd != null).length;
  const enabledCount = visibleGroups.filter(g => g.enabled).length;
  const enabledDefinitions = visibleGroups.filter(g => g.enabled && !g.savedClass).length
    + new Set(visibleGroups.flatMap(g => g.enabled && g.savedClass ? [g.savedClass.id] : [])).size;
  const busy = loadingRules || savingRules || exporting || exportingCalls || attachingCalls;
  const menuItem = 'block w-full px-3 py-1.5 text-left text-[11px] hover:bg-gray-50 disabled:opacity-40 dark:hover:bg-gray-800';

  const menus = (
    <>
      <details className="relative" data-testid="saved-load-menu">
        <summary className="inline-flex cursor-pointer list-none items-center gap-1 rounded-fb border border-emerald-300 px-2 py-0.5 text-[11px] text-emerald-700 hover:bg-emerald-50 dark:border-emerald-700 dark:text-emerald-300 dark:hover:bg-emerald-950/40">
          {loadingRules || attachingCalls ? 'Loading…' : <>Load<ChevronDown size={11} aria-hidden="true" /></>}
        </summary>
        <div className="absolute right-0 z-20 mt-1 w-56 rounded-fb-lg border border-line bg-white py-1 shadow-dropdown dark:border-white/10 dark:bg-dark-surface">
          <button className={menuItem} disabled={busy} onClick={() => void handleLoadRules('replace')}>
            Rules (JSON){visibleGroups.length ? ', replacing these' : ''}
          </button>
          {visibleGroups.length > 0 && (
            <button className={menuItem} disabled={busy} onClick={() => void handleLoadRules('append')}>Rules (JSON), adding to these</button>
          )}
          <button className={menuItem} disabled={busy || attachDatasetIds.length === 0} onClick={() => void handleAttachDerivedLayers()}
            title="Attach a frozen .fiberlayers call bundle as layers of the loaded datasets">
            Matched calls (.fiberlayers)
          </button>
        </div>
      </details>
      {visibleGroups.length > 0 && (
        <details className="relative" data-testid="saved-export-menu">
          <summary className="inline-flex cursor-pointer list-none items-center gap-1 rounded-fb border border-emerald-300 px-2 py-0.5 text-[11px] text-emerald-700 hover:bg-emerald-50 dark:border-emerald-700 dark:text-emerald-300 dark:hover:bg-emerald-950/40">
            {savingRules || exporting || exportingCalls ? 'Exporting…' : <>Export<ChevronDown size={11} aria-hidden="true" /></>}
          </summary>
          <div className="absolute right-0 z-20 mt-1 w-64 rounded-fb-lg border border-line bg-white py-1 shadow-dropdown dark:border-white/10 dark:bg-dark-surface">
            <button className={menuItem} disabled={busy} onClick={() => void handleSaveRules()}
              title="Portable definitions you can load onto other datasets">
              Rules (JSON)
            </button>
            <div className="flex items-center gap-1 pr-2">
              <button className={menuItem} disabled={busy || pinnedCount === 0} onClick={() => void handleExportFasta()}
                title="Reference sequences for MEME, HOMER, FIMO or BLAST">
                Sequences (FASTA)
              </button>
              <label className="flex items-center gap-0.5 text-[11px] text-gray-500" title="Extra bases on each side">
                ±<input type="number" min={0} max={2000} step={5} value={exportFlank}
                  onChange={e => setExportFlank(Math.max(0, Math.min(2000, Number(e.target.value) || 0)))}
                  className="w-12 rounded border border-gray-300 px-1 text-right dark:border-gray-600 dark:bg-gray-900" />
              </label>
            </div>
            <button className={menuItem} disabled={busy || enabledCount === 0 || targetDatasetIds.length === 0}
              onClick={() => void handleSaveDerivedLayers()} title="Exact per-read matches in this view, as a .fiberlayers bundle">
              Matched calls (.fiberlayers)
            </button>
          </div>
        </details>
      )}
      {visibleGroups.length > 0 && (
        <AnalysisButton
          onClick={() => {
            const before = useBrowserStore.getState().footprintGroups;
            const runs = new Set(before.flatMap(g => g.savedClass && g.consensusJobId ? [g.consensusJobId] : []));
            const removed = before.filter(group => !group.autoGeneratedFamily);
            setFootprintGroups(before.filter(group => group.autoGeneratedFamily));
            runs.forEach(jobId => void pushRunTiers(jobId));
            // one step back, for a few seconds
            useUndoToastStore.getState().show('footprints', `Cleared ${definitionCount} saved definition${definitionCount === 1 ? '' : 's'}`, () => {
              setFootprintGroups(restoreRemovedGroups(removed, useBrowserStore.getState().footprintGroups));
              runs.forEach(jobId => void pushRunTiers(jobId));
            });
          }}
          variant="dangerOutline"
          data-testid="saved-clear-all"
          title="Remove all saved definitions (Undo is offered)"
        >
          Clear all
        </AnalysisButton>
      )}
    </>
  );

  const describe = (g: FootprintGroup) => {
    const hasRef = g.referenceAbsStart != null && g.referenceAbsEnd != null;
    if (g.consensusStateId) {
      return hasRef ? `class · ${Math.round(g.referenceAbsEnd! - g.referenceAbsStart!)} bp` : 'class';
    }
    const size = `${g.sizeMin}–${g.sizeMax ?? '∞'} bp`;
    return hasRef ? `${size} at ${chrom}:${Math.round(g.referenceAbsStart!).toLocaleString()}` : `${size} anywhere`;
  };

  return (
    <div className="space-y-2">
      <AnalysisPanelHeader
        title={visibleGroups.length ? `${definitionCount} saved` : 'Nothing saved yet'}
        // One count: say how many are ticked only when that is not all of them (L10).
        detail={visibleGroups.length && enabledDefinitions < definitionCount
          ? `${enabledDefinitions} ticked: shown on reads and compared` : undefined}
        theme="emerald"
        actions={menus}
      />

      {cartMessage && <AnalysisStatus kind={cartMessage.kind} compact>{cartMessage.text}</AnalysisStatus>}

      <p className="text-[11px] text-gray-600 dark:text-gray-300" data-testid="saved-intro">
        Saved keeps class definitions for this session: each one is drawn, filtered, plotted and compared in Co-occupancy.
        It is not the toolbar’s <span className="font-medium">Save</span> (the whole session as a file), and not a star (a starred item stays in its own panel's list).
      </p>
      {visibleGroups.length === 0 && (
        <div className="py-3 text-center text-[11px] text-gray-600 dark:text-gray-300">
          Use <span className="font-medium text-emerald-700 dark:text-emerald-300">Add to Saved</span> on a class in the Classes tab,
          or Cmd/Ctrl-click footprints on reads and save their size ranges.
        </div>
      )}

      <SavedClassesSummary groups={visibleGroups} />

      <div className="space-y-1">
        {visibleGroups.map((g, index) => {
          // A saved recaller class is one card for all its entries, where its first entry is.
          if (g.savedClass) {
            const id = g.savedClass.id;
            if (visibleGroups.findIndex(x => x.savedClass?.id === id) !== index) return null;
            return <SavedClassCard key={`saved-class-${id}`} info={g.savedClass} groups={visibleGroups.filter(x => x.savedClass?.id === id)}
              filtering={activeFilterId === `saved:${id}`} onFilter={groups => onFilterSavedClass?.(groups)}
              targetDatasetIds={targetDatasetIds} chartWidth={chartWidth} />;
          }
          const expanded = expandedId === g.id;
          const isActiveFilter = activeFilterId === g.id;
          const isSelectedFamily = selectedFamilyGroupId === g.id;
          const isState = !!g.consensusStateId || g.familyId != null;
          return (
            <div
              key={g.id}
              data-testid="saved-row"
              data-saved-group-id={g.id}
              className={`rounded border ${isSelectedFamily
                ? 'border-amber-400 bg-amber-50/70 dark:border-amber-500 dark:bg-amber-950/25'
                : isActiveFilter
                  ? 'border-emerald-400 bg-emerald-50/50 dark:bg-emerald-900/20'
                  : 'border-gray-200 dark:border-gray-700'}`}
            >
              <div className="flex items-center gap-1.5 px-2 py-1 text-[11px]">
                <input
                  type="checkbox" checked={g.enabled}
                  onChange={e => updateFootprintGroup(g.id, { enabled: e.target.checked })}
                  className="h-3 w-3 flex-shrink-0"
                  aria-label={`Show and compare ${g.name}`}
                  title="Color matching reads and include in Co-occupancy"
                />
                <input
                  type="color" value={g.color}
                  onChange={e => updateFootprintGroup(g.id, { color: e.target.value })}
                  className="h-4 w-4 flex-shrink-0 cursor-pointer rounded-sm border-0 bg-transparent p-0"
                  title="Color"
                />
                <button
                  onClick={() => {
                    setExpandedId(expanded ? null : g.id);
                    if (!isState) setSelectedFamilyGroupId(null);
                    if (isState) {
                      setSelectedFamilyGroupId(expanded ? null : g.id);
                      if (!expanded && g.consensusStateId && g.consensusJobId && g.sourceDatasetId) {
                        useConsensusViewStore.getState().select({ jobId: g.consensusJobId, datasetId: g.consensusDatasetId ?? g.sourceDatasetId, family: g.consensusStateId });
                      }
                    }
                  }}
                  className="flex min-w-0 flex-1 items-baseline gap-1 text-left"
                  title="Details"
                  aria-expanded={expanded}
                  data-tour="saved-entry-open"
                >
                  <span className="inline-flex w-3 self-center text-gray-500"><DisclosureChevron open={expanded} /></span>
                  <span className="truncate text-gray-800 dark:text-gray-200">{g.name}</span>
                  <span className="truncate text-[11px] text-ink-secondary">{describe(g)}</span>
                </button>
                <AnalysisButton
                  onClick={() => isActiveFilter ? onClearFilter() : onApplyFilter(g)}
                  theme="emerald"
                  variant={isActiveFilter ? 'primary' : 'soft'}
                  className="whitespace-nowrap"
                  title={isActiveFilter ? 'Show all reads again' : 'Show only reads with this footprint'}
                >
                  {isActiveFilter ? 'Filtering' : 'Filter reads'}
                </AnalysisButton>
                <AnalysisButton onClick={() => removeFootprintGroup(g.id)} variant="dangerOutline" className="inline-flex items-center"
                  title="Remove from Saved" aria-label={`Remove ${g.name}`} data-testid="saved-row-remove">
                  <Trash size={12} aria-hidden="true" />
                </AnalysisButton>
              </div>

              {expanded && (
                <div className="space-y-2 border-t border-gray-200 p-2 text-[11px] dark:border-gray-700">
                  <label className="flex items-center gap-1.5">
                    <span className="w-12 text-gray-500">Name</span>
                    <input
                      type="text" value={g.name}
                      onChange={e => updateFootprintGroup(g.id, { name: e.target.value })}
                      className="flex-1 rounded border border-gray-300 bg-white px-1 py-0.5 dark:border-gray-600 dark:bg-gray-800"
                    />
                  </label>

                  <CartEntryInspect group={g} targetDatasetIds={targetDatasetIds} width={chartWidth} />

                  {/* A state matches by its identity: size and overlap don't apply. */}
                  {g.consensusStateId && showDetails && (
                    <div className="break-all text-[11px] text-ink-secondary">Matches reads assigned to class {g.consensusStateId}</div>
                  )}
                  {!g.consensusStateId && (
                  <details className="rounded border border-gray-200 p-2 dark:border-gray-700">
                    <summary className="cursor-pointer text-gray-500">Advanced: matching rule</summary>
                    <div className="mt-2 space-y-2">
                      {/* The layer comes from the footprint the rule was saved from;
                          it can be changed only with analysis details on. */}
                      {!isState && (showDetails
                        ? <LayerSelector value={g.layer ?? null} onChange={layer => updateFootprintGroup(g.id, { layer })} allLabel="Any" title="Layer" variant="chips" />
                        : (
                          <div className="flex items-center gap-1.5">
                            <span className="w-12 text-gray-500">Calls</span>
                            <span className="text-gray-700 dark:text-gray-300">{g.layer ? getLayerLabel(g.layer) : 'Footprints (any layer)'}</span>
                          </div>
                        ))}
                      <label className="flex items-center gap-1.5">
                        <span className="w-12 text-gray-500">Size</span>
                        <input type="number" value={g.sizeMin} min={0} max={500}
                          onChange={e => updateFootprintGroup(g.id, { sizeMin: Math.max(0, Number(e.target.value) || 0) })}
                          className="w-14 rounded border border-gray-300 bg-white px-1 py-0.5 text-right dark:border-gray-600 dark:bg-gray-800" title="Min size (bp)" />
                        <span className="text-ink-secondary">to</span>
                        <input type="number" value={g.sizeMax ?? ''} min={0} max={500} placeholder="∞"
                          onChange={e => { const v = e.target.value.trim(); updateFootprintGroup(g.id, { sizeMax: v === '' ? null : Number(v) }); }}
                          className="w-14 rounded border border-gray-300 bg-white px-1 py-0.5 text-right dark:border-gray-600 dark:bg-gray-800" title="Max size (bp), blank = no limit" />
                        <span className="text-ink-secondary">bp</span>
                      </label>
                      {g.sizeMax != null && g.sizeMin > g.sizeMax && (
                        <div className="text-[11px] text-amber-700 dark:text-amber-300">Minimum is above maximum: nothing matches.</div>
                      )}
                      {g.familyId != null && (
                        <label className="flex items-center gap-1.5">
                          <span className="w-12 text-gray-500">Min conf.</span>
                          <input type="number" min={0} max={1} step={0.05} value={g.minFamilyConfidence ?? 0}
                            onChange={e => updateFootprintGroup(g.id, { minFamilyConfidence: Math.max(0, Math.min(1, Number(e.target.value) || 0)) })}
                            className="w-14 rounded border border-gray-300 bg-white px-1 py-0.5 text-right dark:border-gray-600 dark:bg-gray-800" />
                        </label>
                      )}
                      {g.referenceAbsStart != null && g.referenceAbsEnd != null && (() => {
                        // Old sessions stored overlapMode; show its equivalent coverage.
                        let fpCov = g.minFpCoverage ?? 0;
                        let tgtCov = g.minTargetCoverage ?? 0;
                        if (fpCov === 0 && tgtCov === 0 && g.overlapMode) {
                          if (g.overlapMode === 'contains_target') tgtCov = 1;
                          else if (g.overlapMode === 'contained_by_target') fpCov = 1;
                          else if (g.overlapMode === 'fraction') { fpCov = g.overlapFraction; tgtCov = g.overlapFraction; }
                        }
                        const pct = (v: number) => Math.round(v * 100);
                        const frac = (v: number) => Math.max(0, Math.min(100, v)) / 100;
                        // Editing either value migrates an old rule: both coverages are
                        // written as shown and the legacy mode is dropped, so setting
                        // them to 0 means any overlap instead of reviving the old mode.
                        const setCoverage = (patch: { minFpCoverage?: number; minTargetCoverage?: number }) =>
                          updateFootprintGroup(g.id, {
                            minFpCoverage: fpCov, minTargetCoverage: tgtCov, ...patch,
                            overlapMode: undefined, overlapFraction: undefined,
                          });
                        return (
                          <div className="flex flex-wrap items-center gap-1.5">
                            <span className="w-12 text-gray-500">Overlap</span>
                            <label className="flex items-center gap-1" title="How much of a read's footprint must lie inside this position">
                              <span className="text-[11px] text-gray-500">footprint inside ≥</span>
                              <input type="number" step={5} min={0} max={100} value={pct(fpCov)}
                                onChange={e => setCoverage({ minFpCoverage: frac(Number(e.target.value) || 0) })}
                                className="w-12 rounded border border-gray-300 bg-white px-1 py-0.5 text-right dark:border-gray-600 dark:bg-gray-800" />
                              <span className="text-ink-secondary">%</span>
                            </label>
                            <label className="flex items-center gap-1" title="How much of this position a read's footprint must cover">
                              <span className="text-[11px] text-gray-500">position covered ≥</span>
                              <input type="number" step={5} min={0} max={100} value={pct(tgtCov)}
                                onChange={e => setCoverage({ minTargetCoverage: frac(Number(e.target.value) || 0) })}
                                className="w-12 rounded border border-gray-300 bg-white px-1 py-0.5 text-right dark:border-gray-600 dark:bg-gray-800" />
                              <span className="text-ink-secondary">%</span>
                            </label>
                            {!isState && (
                              <AnalysisButton onClick={() => updateFootprintGroup(g.id, { referenceAbsStart: null, referenceAbsEnd: null })}
                                variant="dangerOutline" className="ml-auto" title="Match footprints of this size anywhere, not just here">
                                Match anywhere
                              </AnalysisButton>
                            )}
                          </div>
                        );
                      })()}
                    </div>
                  </details>
                  )}
                </div>
              )}
            </div>
          );
        })}
      </div>
    </div>
  );
}
