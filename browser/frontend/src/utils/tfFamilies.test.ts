import { describe, expect, it } from 'vitest';
import {
  discoverTfFamilyGroups,
  passesFamilyAssignmentConfidence,
  tfFamilyColor,
  tfFamilyDisplayGeometry,
  tfFamilyMetadata,
  tfFamilyRenderGeometry,
} from './tfFamilies';

describe('BAM-native TF families', () => {
  it('applies Cart confidence thresholds only to ordinary assignments', () => {
    const assignment = {
      familyId: 7,
      familyConfidence: 0.8,
      confidenceKind: 'assignment' as const,
    };
    const latentSupport = {
      familyId: 7,
      familyConfidence: 0.99,
      confidenceKind: 'latent-support' as const,
    };
    expect(passesFamilyAssignmentConfidence(assignment, 0.75)).toBe(true);
    expect(passesFamilyAssignmentConfidence(assignment, 0.85)).toBe(false);
    expect(passesFamilyAssignmentConfidence(latentSupport, 0.75)).toBe(false);
    expect(passesFamilyAssignmentConfidence(null, 0.75)).toBe(false);
    expect(passesFamilyAssignmentConfidence(latentSupport, 0)).toBe(true);
    const crossSupport = {
      familyId: 7,
      familyConfidence: 0.92,
      confidenceKind: 'cross-support' as const,
    };
    expect(passesFamilyAssignmentConfidence(crossSupport, 0.9)).toBe(true);
    expect(passesFamilyAssignmentConfidence(crossSupport, 0.95)).toBe(false);
  });

  it('reads fi/fq without confusing them with strand-rescue q0/q1/q2', () => {
    const metadata = tfFamilyMetadata({
      intervals: [[1, 10, 9]],
      quality_names: ['q0', 'q1', 'q2', 'fi', 'fq'],
      qualities: [[255], [10], [20], [7], [204]],
    }, 0);
    expect(metadata).toEqual({
      familyId: 7,
      familyConfidence: 0.8,
      confidenceKind: 'assignment',
    });
    expect(tfFamilyColor(7)).not.toBe(tfFamilyColor(31));
    expect(new Set(Array.from({ length: 255 }, (_, index) => tfFamilyColor(index + 1))).size).toBe(255);
    expect(tfFamilyMetadata({
      intervals: [[1, 10, 9]],
      annotation_names: ['fhlt_deadbeefdeadbeef_R0'],
      quality_names: ['q0', 'q1', 'q2', 'fi', 'fq'],
      qualities: [[10], [200], [150], [7], [252]],
    }, 0)?.confidenceKind).toBe('latent-support');
    expect(tfFamilyMetadata({
      intervals: [[1, 10, 9]],
      annotation_names: ['fhxcr_cross_family'],
      quality_names: ['fi', 'fq', 'xq'],
      qualities: [[7], [250], [153]],
    }, 0)).toEqual({
      familyId: 7,
      familyConfidence: 0.6,
      annotationName: 'fhxcr_cross_family',
      confidenceKind: 'cross-support',
    });
  });

  it('creates separate cart entries for reused IDs at distant loci', () => {
    const groups = discoverTfFamilyGroups([{
      id: 'r1',
      intervals: [],
      layers: {
        tf_sr: {
          intervals: [[10, 30, 20], [500, 520, 20], [12, 28, 16]],
          quality_names: ['q0', 'q1', 'q2', 'fi', 'fq'],
          qualities: [[255, 255, 255], [0, 0, 0], [0, 0, 0], [7, 7, 8], [230, 220, 250]],
        },
      },
    }], 'chr1', 1000, 'ds1', 'panel-1');

    expect(groups).toHaveLength(3);
    expect(groups.map(group => group.familyId)).toEqual([7, 7, 8]);
    expect(groups[0].referenceAbsStart).toBe(1010);
    expect(groups[0].familyModelAbsStart).toBe(1010);
    expect(groups[0].familyModelAbsEnd).toBe(1030);
    expect(groups[0].familyBoundaryMode).toBe('both');
    expect(groups[1].referenceAbsStart).toBe(1500);
    expect(groups.every(group => group.autoGeneratedFamily)).toBe(true);
    expect(groups.every(group => group.sourceViewKey === 'panel-1')).toBe(true);
    expect(groups.every(group => group.enabled === false)).toBe(true);
  });

  it('uses unclipped source bounds for stable family references', () => {
    const groups = discoverTfFamilyGroups([{
      id: 'edge-read',
      intervals: [],
      layers: {
        tf_sr: {
          intervals: [[0, 3, 5]],
          source_intervals: [[-2, 3, 5]],
          quality_names: ['q0', 'q1', 'q2', 'fi', 'fq'],
          qualities: [[255], [0], [0], [7], [230]],
        },
      },
    }], 'chr1', 1000, 'ds1');
    expect(groups[0].referenceAbsStart).toBe(998);
    expect(groups[0].referenceAbsEnd).toBe(1003);
  });

  it('does not let latent consumers move the frozen family display model', () => {
    const groups = discoverTfFamilyGroups([{
      id: 'r1',
      intervals: [],
      layers: {
        tf_sr: {
          intervals: [[10, 30, 20], [2, 42, 40]],
          annotation_names: ['', 'fhlt_deadbeefdeadbeef_R0'],
          quality_names: ['q0', 'q1', 'q2', 'fi', 'fq'],
          qualities: [[255, 10], [0, 10], [0, 10], [7, 7], [230, 230]],
        },
      },
    }], 'chr1', 1000, 'ds1');

    expect(groups).toHaveLength(1);
    expect(groups[0].referenceAbsStart).toBe(1010);
    expect(groups[0].referenceAbsEnd).toBe(1030);
  });

  it('does not let a latent consumer bridge two reused-ID locus components', () => {
    const groups = discoverTfFamilyGroups([{
      id: 'bridge',
      intervals: [],
      layers: {
        tf_sr: {
          intervals: [[10, 30, 20], [100, 120, 20], [35, 95, 60]],
          annotation_names: ['', '', 'fhlt_deadbeefdeadbeef_R0'],
          quality_names: ['q0', 'q1', 'q2', 'fi', 'fq'],
          qualities: [[255, 255, 10], [0, 0, 10], [0, 0, 10], [7, 7, 7], [230, 230, 230]],
        },
      },
    }], 'chr1', 1000, 'ds1');

    expect(groups).toHaveLength(2);
    expect(groups.map(group => group.referenceAbsStart)).toEqual([1010, 1100]);
    expect(groups.map(group => group.familyModelAbsEnd)).toEqual([1030, 1120]);
  });

  it('discovers every member of a shared multifamily latent configuration', () => {
    const groups = discoverTfFamilyGroups([{
      id: 'hybrid',
      intervals: [],
      layers: {
        tf_sr: {
          intervals: [[10, 39, 29], [63, 87, 24]],
          annotation_names: [
            'fhlt_deadbeefdeadbeef_R0',
            'fhlt_deadbeefdeadbeef_R1',
          ],
          quality_names: ['q0', 'q1', 'q2', 'fi', 'fq'],
          qualities: [[251, 251], [255, 255], [79, 255], [21, 22], [253, 213]],
        },
      },
    }], 'chr19', 47515550, 'napa');

    expect(groups.map(group => group.familyId)).toEqual([21, 22]);
    expect(groups.map(group => group.familyBoundaryMode)).toEqual(['molecule', 'molecule']);
    expect(groups.map(group => group.enabled)).toEqual([false, false]);
    expect(groups[0].referenceAbsStart).toBe(47515560);
    expect(groups[1].referenceAbsStart).toBe(47515613);
  });

  it('uses the robust model boundary while retaining per-family display choice', () => {
    const groups = discoverTfFamilyGroups([{
      id: 'r1',
      intervals: [],
      layers: {
        tf_sr: {
          intervals: [[10, 30, 20], [12, 28, 16], [14, 32, 18]],
          quality_names: ['fi', 'fq'],
          qualities: [[7, 7, 7], [255, 255, 255]],
        },
      },
    }], 'chr1', 1000, 'ds1');

    expect(groups[0].referenceAbsStart).toBe(1010);
    expect(groups[0].referenceAbsEnd).toBe(1032);
    expect(groups[0].familyModelAbsStart).toBe(1012);
    expect(groups[0].familyModelAbsEnd).toBe(1030);
    groups[0].familyBoundaryMode = 'family';
    expect(tfFamilyDisplayGeometry(groups, 'ds1', 7, 1014, 1032)).toEqual({
      groupId: groups[0].id,
      mode: 'family',
      start: 1012,
      end: 1030,
    });
    expect(tfFamilyDisplayGeometry(groups, 'other-dataset', 7, 1014, 1032)).toBeNull();
    // The same family slot on another chromosome, or in another panel's own
    // discovery, lends no geometry.
    expect(groups[0].referenceChrom).toBe('chr1');
    expect(tfFamilyDisplayGeometry(groups, 'ds1', 7, 1014, 1032, undefined, undefined, undefined, 'chr2')).toBeNull();
    expect(tfFamilyDisplayGeometry(groups, 'ds1', 7, 1014, 1032, undefined, undefined, undefined, '1', 'ds1')?.groupId)
      .toBe(groups[0].id);
    expect(tfFamilyDisplayGeometry(groups, 'ds1', 7, 1014, 1032, undefined, undefined, undefined, 'chr1', 'copy')).toBeNull();
  });

  it('keeps the adjusted molecule as the fill and the shared family as the outline', () => {
    expect(tfFamilyRenderGeometry(1014, 1032, {
      groupId: 'family-7',
      mode: 'both',
      start: 1012,
      end: 1030,
    })).toEqual({
      fillStart: 1014,
      fillEnd: 1032,
      outlineStart: 1012,
      outlineEnd: 1030,
    });
    expect(tfFamilyRenderGeometry(1014, 1032, {
      groupId: 'family-7',
      mode: 'family',
      start: 1012,
      end: 1030,
    })).toEqual({
      fillStart: 1012,
      fillEnd: 1030,
      outlineStart: null,
      outlineEnd: null,
    });
  });
});

it('discovers CR/XCR by AN identity and treats declared confidence as unavailable',()=>{
  const layer={intervals:[[10,30,20],[10,30,20]] as [number,number,number][],
    quality_names:['tq','fi','fq','op'],qualities:[[80,80],[1,1],[0,0],[20,20]],
    annotation_names:['fhcr_first','fhcr_second'],family_confidence_kind:'unavailable' as const};
  const metadata=tfFamilyMetadata(layer,0)!;
  expect(metadata.confidenceKind).toBe('unavailable');
  expect(passesFamilyAssignmentConfidence(metadata,0)).toBe(true);
  expect(passesFamilyAssignmentConfidence(metadata,.01)).toBe(false);
  const groups=discoverTfFamilyGroups([{id:'r',intervals:[],layers:{tf_consensus:layer}}],'chr1',100,'d');
  expect(groups).toHaveLength(2);
  expect(groups.map(g=>g.familyAnnotationName)).toEqual(['fhcr_first','fhcr_second']);
  expect(groups[0].color).not.toBe(groups[1].color);
  expect(groups.every(g=>g.layer==='tf_consensus'&&!g.enabled)).toBe(true);
  expect(tfFamilyColor(1,'fhcr_first')).toBe(tfFamilyColor(99,'fhcr_first'));
});


it('keeps named assignment identity for color and excludes unrelated unnamed geometry',()=>{
  const layer={intervals:[[10,30,20]] as [number,number,number][],
    quality_names:['fi','fq'],qualities:[[7],[255]],annotation_names:['fhcr_model']};
  expect(tfFamilyMetadata(layer,0)?.annotationName).toBe('fhcr_model');
  const groups=discoverTfFamilyGroups([{id:'r',intervals:[],layers:{tf_consensus:layer}}],'chr1',100,'d');
  const unnamed={...groups[0],id:'unrelated',familyId:8,familyAnnotationName:undefined,
    familyModelAbsStart:112,familyModelAbsEnd:128};
  // An explicit global name must win even when an unrelated local slot is nearer.
  expect(tfFamilyDisplayGeometry([unnamed,...groups],'d',7,112,128,'tf_consensus',1,'fhcr_model')?.groupId).toBe(groups[0].id);
  expect(tfFamilyDisplayGeometry(groups,'d',7,112,128)?.groupId).toBe(groups[0].id);
});
