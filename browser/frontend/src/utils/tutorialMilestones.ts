/**
 * What a tutorial step can wait for or check, shared with the backend planner
 * through data/tutorialMilestones.json:
 *
 * - **milestones** are things the user does (`clustered`, `footprint_saved`):
 *   a `try_it` step waits for one. Each is judged against the state when the
 *   step began, so something already true doesn't pass by itself.
 * - **conditions** are facts about the current state (`has_clusters`,
 *   `panel_open:<type>`): a step's `skip_if` drops it when one holds, and its
 *   `requires` shows a short prerequisite note first when one doesn't.
 */
import catalog from '../data/tutorialMilestones.json';
import { getStatus } from '../api/status';
import { useBrowserStore, type BrowserState } from '../stores/browserStore';
import { computeCopilotDiagnostics } from './copilotDiagnostics';
import { TUTORIAL_EVENT } from './tutorialEvents';

export interface TutorialMilestone { id: string; description: string; anchor: string; parameter?: string }
export interface TutorialCondition extends TutorialMilestone { hint: string }

const CATALOG = catalog as {
  panel_types: string[];
  milestones: TutorialMilestone[];
  conditions: TutorialCondition[];
};

export const TUTORIAL_PANEL_TYPES: readonly string[] = CATALOG.panel_types;
export const TUTORIAL_MILESTONES: readonly TutorialMilestone[] = CATALOG.milestones;
export const TUTORIAL_CONDITIONS: readonly TutorialCondition[] = CATALOG.conditions;

export { TUTORIAL_EVENT, emitTutorialEvent } from './tutorialEvents';

/** `panel_open:cluster-detail` → ['panel_open', 'cluster-detail']. */
function splitParam(id: string): [string, string] {
  const i = id.indexOf(':');
  return i < 0 ? [id, ''] : [id.slice(0, i), id.slice(i + 1)];
}

function catalogEntry<T extends TutorialMilestone>(entries: readonly T[], id: string): T | undefined {
  const [base, param] = splitParam(id);
  return entries.find(e => (param ? e.id.startsWith(`${base}:`) && TUTORIAL_PANEL_TYPES.includes(param) : e.id === base));
}

export const milestoneById = (id: string) => catalogEntry(TUTORIAL_MILESTONES, id);
export const conditionById = (id: string) => catalogEntry(TUTORIAL_CONDITIONS, id);

// ── State helpers ─────────────────────────────────────────────────────

const anyNonEmpty = (record: Record<string, unknown> | undefined, test: (v: unknown) => boolean) =>
  Object.values(record ?? {}).some(test);
const nonEmptyObject = (v: unknown) => !!v && typeof v === 'object' && Object.keys(v as object).length > 0;
const nonEmptySet = (v: unknown) => v instanceof Set && v.size > 0;
const panelOpen = (s: BrowserState, type: string) => s.panels.some(p => p.contentType === type && !p.collapsed);
const datasetPanelCount = (s: BrowserState) => s.panels.filter(p => p.contentType === 'dataset').length;
const strandPanelCount = (s: BrowserState) => s.panels.filter(p => p.contentType === 'dataset' && p.strand).length;
const peakCount = (s: BrowserState) => Object.values(s.peaksByRule ?? {}).reduce((n, peaks) => n + (peaks?.length ?? 0), 0);
const savedFootprints = (s: BrowserState) => (s.footprintGroups ?? []).filter(g => !g.autoGeneratedFamily);
const trackCount = (s: BrowserState) => (s.orthogonalTracks?.length ?? 0) + (s.compositeTracks?.length ?? 0);
const distinctClusters = (assignments: Record<string, number> | undefined) => new Set(Object.values(assignments ?? {})).size;

/** Keys whose value changed since the baseline (store updates replace what they change). */
function changedKeys<T>(now: Record<string, T> | undefined, base: Record<string, T> | undefined): string[] {
  if (now === base) return [];
  return Object.keys(now ?? {}).filter(k => (now ?? {})[k] !== (base ?? {})[k]);
}

// ── Milestones: did the user do it since the step began? ─────────────

export function milestoneReached(id: string, s: BrowserState, base: BrowserState, events: ReadonlySet<string> = new Set()): boolean {
  const [name, param] = splitParam(id);
  switch (name) {
    case 'dataset_loaded': return s.datasets.some(d => !base.datasets.some(b => b.id === d.id));
    case 'genome_loaded': return (s.currentGenome !== base.currentGenome && !!s.currentGenome)
      || (s.hasFasta && !base.hasFasta) || (s.chroms !== base.chroms && s.chroms.length > 0 && s.hasFasta);
    case 'navigated': return s.chrom !== base.chrom || s.start !== base.start || s.end !== base.end;
    case 'peaks_scanned': return s.peaksByRule !== base.peaksByRule && peakCount(s) > 0;
    case 'peak_selected': return s.selectedPeaks !== base.selectedPeaks && s.selectedPeaks.size > 0;
    case 'clustered': return changedKeys(s.clusterAssignments, base.clusterAssignments)
      .some(k => nonEmptyObject(s.clusterAssignments[k]));
    case 'clusters_merged': return changedKeys(s.clusterAssignments, base.clusterAssignments).some(k => {
      const before = distinctClusters(base.clusterAssignments?.[k]);
      const after = distinctClusters(s.clusterAssignments[k]);
      return before > 0 && after > 0 && after < before;
    });
    case 'cluster_focused': return changedKeys(s.clusterFocus, base.clusterFocus).some(k => nonEmptySet(s.clusterFocus[k]));
    case 'footprint_selected': return s.selectedFootprints !== base.selectedFootprints && s.selectedFootprints.length > 0;
    case 'gene_selected': return s.selectedGenes !== base.selectedGenes && (s.selectedGenes?.length ?? 0) > 0;
    case 'footprint_saved': return savedFootprints(s).length > savedFootprints(base).length;
    case 'reads_selected': return changedKeys(s.selectedReadIds, base.selectedReadIds).some(k => nonEmptySet(s.selectedReadIds[k]));
    case 'filter_applied': return changedKeys(s.filteredReadIds, base.filteredReadIds).some(k => s.filteredReadIds[k] != null);
    case 'filter_cleared': return Object.keys(base.filteredReadIds ?? {})
      .some(k => base.filteredReadIds[k] != null && s.filteredReadIds[k] == null);
    case 'sorted': return changedKeys(s.readSortOrder, base.readSortOrder).some(k => (s.readSortOrder[k]?.length ?? 0) > 0)
      || changedKeys(s.clusterOrder, base.clusterOrder).some(k => (s.clusterOrder[k]?.length ?? 0) > 0);
    case 'panel_opened': return panelOpen(s, param) && !panelOpen(base, param);
    case 'panel_copy_made': return datasetPanelCount(s) > datasetPanelCount(base);
    case 'strand_split': return strandPanelCount(s) > strandPanelCount(base);
    case 'primers_designed': return s.primer.designResults !== base.primer.designResults && s.primer.designResults.length > 0;
    case 'track_added': return trackCount(s) > trackCount(base);
    case 'session_saved': return events.has('session_saved');
    case 'undo_used': return s._historyPointer < base._historyPointer;
    default: return false;
  }
}

// ── Conditions: does it hold now? ─────────────────────────────────────

export async function conditionHolds(id: string, s: BrowserState = useBrowserStore.getState()): Promise<boolean> {
  const [name, param] = splitParam(id);
  switch (name) {
    // The troubleshooting diagnostics already know these two.
    case 'has_dataset': return !computeCopilotDiagnostics(s).some(d => d.code === 'no_datasets');
    case 'has_reference': return !computeCopilotDiagnostics(s).some(d => d.code === 'no_reference');
    case 'has_gtf':
      if ((s.genes?.length ?? 0) > 0) return true;
      try { return Boolean((await getStatus()).has_gtf); } catch { return false; }
    case 'has_peaks': return peakCount(s) > 0;
    case 'has_selected_peak': return s.selectedPeaks.size > 0;
    case 'has_clusters': return anyNonEmpty(s.clusterAssignments, nonEmptyObject);
    case 'has_selected_footprint': return s.selectedFootprints.length > 0;
    case 'has_saved_footprints': return savedFootprints(s).length > 0;
    case 'has_selected_reads': return anyNonEmpty(s.selectedReadIds, nonEmptySet);
    case 'has_selected_gene': return (s.selectedGenes?.length ?? 0) > 0;
    case 'has_filter': return anyNonEmpty(s.filteredReadIds, v => v != null);
    case 'has_panel_copy': {
      const perDataset = new Map<string, number>();
      for (const p of s.panels) if (p.contentType === 'dataset' && p.datasetId) perDataset.set(p.datasetId, (perDataset.get(p.datasetId) ?? 0) + 1);
      return [...perDataset.values()].some(n => n > 1);
    }
    case 'has_strand_split': return strandPanelCount(s) > 0;
    case 'has_tracks': return trackCount(s) > 0;
    case 'has_primers': return (s.primer.designResults?.length ?? 0) > 0 || (s.primer.savedPrimers?.length ?? 0) > 0 || !!s.primer.pair;
    case 'panel_open': return panelOpen(s, param);
    default: return false;
  }
}

// ── Waiting ───────────────────────────────────────────────────────────

export interface Watch<T> { promise: Promise<T>; cancel: () => void }

/** Resolves once the user reaches the milestone (baseline: now). A store subscription, not polling. */
export function watchMilestone(id: string): Watch<void> {
  const base = useBrowserStore.getState();
  const events = new Set<string>();
  let cancel = () => {};
  const promise = new Promise<void>(resolve => {
    const check = () => {
      if (milestoneReached(id, useBrowserStore.getState(), base, events)) { cancel(); resolve(); }
    };
    const onEvent = (e: Event) => { events.add(String((e as CustomEvent).detail)); check(); };
    const unsubscribe = useBrowserStore.subscribe(check);
    window.addEventListener(TUTORIAL_EVENT, onEvent);
    cancel = () => { unsubscribe(); window.removeEventListener(TUTORIAL_EVENT, onEvent); };
  });
  return { promise, cancel };
}

/** Resolves once the condition holds (checked on each store change). */
export function watchCondition(id: string): Watch<void> {
  let cancel = () => {};
  const promise = new Promise<void>(resolve => {
    let checking = false;
    let again = false;
    let done = false;
    // Checks can be async (has_gtf asks the server); a change during one is
    // checked again right after, so it isn't missed.
    const check = async (): Promise<void> => {
      if (done) return;
      if (checking) { again = true; return; }
      checking = true;
      try {
        if (await conditionHolds(id)) { done = true; cancel(); resolve(); }
      } finally { checking = false; }
      if (again && !done) { again = false; await check(); }
    };
    const unsubscribe = useBrowserStore.subscribe(() => { void check(); });
    cancel = () => { done = true; unsubscribe(); };
    void check();
  });
  return { promise, cancel };
}
