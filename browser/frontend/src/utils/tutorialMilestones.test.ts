import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { useBrowserStore, type BrowserState } from '../stores/browserStore';
import { conditionById, conditionHolds, milestoneById, milestoneReached, watchCondition, watchMilestone } from './tutorialMilestones';
import { emitTutorialEvent } from './tutorialEvents';

let initial: BrowserState;
beforeEach(() => { initial = useBrowserStore.getState(); });
afterEach(() => { useBrowserStore.setState(initial, true); });

const set = (patch: Partial<BrowserState>) => useBrowserStore.setState(patch as never);
const now = () => useBrowserStore.getState();

describe('tutorial milestones', () => {
  it('parses plain and panel ids', () => {
    expect(milestoneById('clustered')?.anchor).toBe('cluster-button');
    expect(milestoneById('panel_opened:footprint-analysis')).toBeTruthy();
    expect(milestoneById('panel_opened:nope')).toBeUndefined();
    expect(conditionById('panel_open:cluster-detail')?.hint).toMatch(/Open the panel/);
  });

  it('judges what changed since the step began, not what was already true', () => {
    set({ clusterAssignments: { ds1: { r1: 0, r2: 1 } } });
    const base = now();
    expect(milestoneReached('clustered', now(), base)).toBe(false);
    set({ clusterAssignments: { ds1: { r1: 0, r2: 1, r3: 2 } } });
    expect(milestoneReached('clustered', now(), base)).toBe(true);
    expect(milestoneReached('clusters_merged', now(), base)).toBe(false);
    set({ clusterAssignments: { ds1: { r1: 0, r2: 0, r3: 0 } } });
    expect(milestoneReached('clusters_merged', now(), base)).toBe(true);
  });

  it('sees navigation, selections, filters and undo', () => {
    const base = now();
    set({ start: base.start + 100, end: base.end + 100 });
    expect(milestoneReached('navigated', now(), base)).toBe(true);
    set({ selectedPeaks: new Set([3]) });
    expect(milestoneReached('peak_selected', now(), base)).toBe(true);
    set({ filteredReadIds: { ds1: new Set<string>() } });
    expect(milestoneReached('filter_applied', now(), base)).toBe(true);
    const filtered = now();
    set({ filteredReadIds: { ds1: null } });
    expect(milestoneReached('filter_cleared', now(), filtered)).toBe(true);
    set({ _historyPointer: base._historyPointer - 1 } as Partial<BrowserState>);
    expect(milestoneReached('undo_used', now(), base)).toBe(true);
  });

  it('waits on the store and on window events', async () => {
    const watch = watchMilestone('footprint_selected');
    set({ selectedFootprints: [{ datasetId: 'ds1', readId: 'r1', start: 10, end: 20 } as never] });
    await expect(watch.promise).resolves.toBeUndefined();
    const saved = watchMilestone('session_saved');
    emitTutorialEvent('session_saved');
    await expect(saved.promise).resolves.toBeUndefined();
  });
});

describe('tutorial conditions', () => {
  it('reads the current state', async () => {
    set({ footprintGroups: [] as never, selectedPeaks: new Set() });
    expect(await conditionHolds('has_saved_footprints')).toBe(false);
    expect(await conditionHolds('has_selected_peak')).toBe(false);
    set({ footprintGroups: [{ id: 'g1', name: 'A', enabled: true } as never], selectedPeaks: new Set([1]) });
    expect(await conditionHolds('has_saved_footprints')).toBe(true);
    expect(await conditionHolds('has_selected_peak')).toBe(true);
    // Auto-generated families aren't saved footprints.
    set({ footprintGroups: [{ id: 'f1', name: 'fam', enabled: true, autoGeneratedFamily: true } as never] });
    expect(await conditionHolds('has_saved_footprints')).toBe(false);
  });

  it('resolves a wait once the condition holds', async () => {
    set({ selectedReadIds: {} as never });
    const watch = watchCondition('has_selected_reads');
    set({ selectedReadIds: { ds1: new Set(['r1']) } as never });
    await expect(watch.promise).resolves.toBeUndefined();
  });
});
