/**
 * browser/data/figure_defaults.json is what the headless Python renderer
 * (browser/services/figure) knows about the browser when no browser state is
 * available: the initial settings, track order and heights, layer colours and
 * labels, and sample cases for the default metaprofile. This test fails when
 * the file is stale; regenerate it with
 *
 *   WRITE_FIGURE_DEFAULTS=1 npx vitest run src/utils/figureDefaults.test.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { useBrowserStore } from '../stores/browserStore';
import { serializeState } from '../stores/historySlice';
import { createDefaultSubTracks } from '../stores/utils';
import { DEFAULT_METAPROFILE_ID } from '../types/dataset';
import { DEFAULT_COLORMAP } from '../types';
import { getLayerColor, getLayerLabel, getMetaprofileSourceEntries } from './layerColors';
import * as constants from '../components/tracks/TrackContainerConstants';
import { PANEL_HEADER_HEIGHT } from '../components/tracks/PanelHeader';

const FILE = path.resolve(__dirname, '../../../data/figure_defaults.json');

const SETTINGS = [
  'readRowHeight', 'allReadsDisplayCap', 'backgroundReadCap', 'spanningOnly', 'readDisplayMode',
  'enabledModTypes', 'enabledMetaProfiles', 'fillReadHeight', 'readSeparatorMode', 'readSeparatorMinHeight',
  'readSeparatorWidth', 'subnucleosomalThreshold', 'accessibilityThreshold', 'maxRegionForReads', 'clusterK',
  'clusterMethod', 'motifThreshold', 'isReversed', 'peakRules', 'peakSettings', 'hideTerminalGaps',
  'terminalGapThreshold', 'fillSmallGaps', 'fillGapSize', 'minFpQuality', 'showDuplicateReads', 'minFootprints', 'analysisSampleSeed',
] as const;

const LAYER_KEYS = [
  'nuc', 'footprint', 'tf', 'fire', 'msp', 'deam', 'deam_opportunity', 'm6a', 'mod', 'm5c', 'nuc_sr', 'tf_sr',
  'tf_consensus', 'tf_cross_consensus', 'ddda_mcg', 'ddda_mcg_hemi', 'tf_cr', 'tf_xcr', 'pol2', 'ctcf', 'enhancer',
];

const METAPROFILE_CASES = [
  { layer_type: 'bam', available_layers: { nuc: true, tf: true, msp: true, deam: true } },
  { layer_type: 'bam', available_layers: { footprint: true, msp: true } },
  { layer_type: 'bigbed', available_layers: { nuc: true, tf: true, m6a: true, pol2: true } },
];

function buildDefaults() {
  const state = serializeState(useBrowserStore.getState()) as unknown as Record<string, unknown>;
  return {
    comment: 'Generated by browser/frontend/src/utils/figureDefaults.test.ts; do not edit by hand.',
    settings: Object.fromEntries(SETTINGS.map(key => [key, state[key] ?? null])),
    activeColormap: DEFAULT_COLORMAP,
    defaultSubTracks: createDefaultSubTracks([], [{ id: DEFAULT_METAPROFILE_ID }]),
    defaultMetaprofileId: DEFAULT_METAPROFILE_ID,
    heights: {
      panelHeader: PANEL_HEADER_HEIGHT,
      axis: constants.AXIS_HEIGHT, meta: constants.META_HEIGHT, fire: constants.FIRE_HEIGHT,
      gene: constants.GENE_HEIGHT, ortho: constants.ORTHO_HEIGHT, annotation: constants.ANNOTATION_HEIGHT,
      sequence: constants.SEQUENCE_HEIGHT, capture: constants.CAPTURE_HEIGHT, primer: constants.PRIMER_HEIGHT,
      microc: constants.MICROC_HEIGHT, coacc: constants.COACC_HEIGHT,
    },
    trackColors: constants.TRACK_COLORS,
    layers: Object.fromEntries(LAYER_KEYS.map(key => [key, { color: getLayerColor(key), label: getLayerLabel(key) }])),
    metaprofileCases: METAPROFILE_CASES.map(dataset => ({
      dataset,
      sources: getMetaprofileSourceEntries([dataset]).map(entry => ({
        key: entry.key, label: entry.label, color: getLayerColor(entry.key),
        visible: entry.key === 'nuc' || entry.key === 'footprint' || entry.key === 'tf',
      })),
    })),
  };
}

describe('figure defaults for the headless renderer', () => {
  it('browser/data/figure_defaults.json matches the browser', () => {
    const expected = JSON.parse(JSON.stringify(buildDefaults()));
    if (process.env.WRITE_FIGURE_DEFAULTS) {
      writeFileSync(FILE, JSON.stringify(expected, null, 2) + '\n');
      return;
    }
    const actual = JSON.parse(readFileSync(FILE, 'utf8'));
    expect(actual, 'Regenerate with WRITE_FIGURE_DEFAULTS=1 npx vitest run src/utils/figureDefaults.test.ts').toEqual(expected);
  });
});
